import { fireEvent, render, screen, waitFor, cleanup } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { TDSMobileAITProvider } from '@toss/tds-mobile-ait';
import App from './App';
import { StrictMode } from 'react';
import { graniteEvent } from '@apps-in-toss/web-framework';
const storage = vi.hoisted(() => ({ value: null as string | null, fail: false, readFail: false, readPending: null as null | Promise<void>, pending: null as null | Promise<void>, nativeBack: undefined as undefined | (() => void), unlisten: vi.fn() }));
vi.mock('@apps-in-toss/web-framework', () => ({ graniteEvent: { addEventListener: vi.fn((_event: string, handlers: { onEvent: () => void }) => { storage.nativeBack = handlers.onEvent; return storage.unlisten; }) }, Storage: { getItem: vi.fn(async () => { if (storage.readFail) throw new Error('read failed'); if (storage.readPending) await storage.readPending; return storage.value; }), setItem: vi.fn(async (_key: string, value: string) => { if (storage.fail) throw new Error('write failed'); if (storage.pending) await storage.pending; storage.value = value; }) } }));
Object.defineProperty(window, 'matchMedia', { value: () => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn(), addListener: vi.fn(), removeListener: vi.fn() }) });
beforeEach(() => { storage.value = null; storage.fail = false; storage.readFail = false; storage.readPending = null; storage.pending = null; storage.nativeBack = undefined; storage.unlisten.mockClear(); window.history.replaceState(null, '', '/'); });
afterEach(cleanup);
const start = () => render(<TDSMobileAITProvider brandPrimaryColor="#555555"><App /></TDSMobileAITProvider>);

describe('navigation and persistence', () => {
  it('creates, cancels and edits while preserving the record ID', async () => {
    start();
    fireEvent.click(await screen.findByRole('button', { name: '첫 구독 추가' }));
    fireEvent.click(screen.getByRole('button', { name: '취소' }));
    fireEvent.click(await screen.findByRole('button', { name: '첫 구독 추가' }));
    fireEvent.change(screen.getByLabelText('서비스명'), { target: { value: '음악' } });
    fireEvent.change(screen.getByLabelText('금액 (원)'), { target: { value: '1000' } });
    fireEvent.click(screen.getByRole('button', { name: '저장' }));
    fireEvent.click(await screen.findByRole('button', { name: /음악/ }));
    const id = JSON.parse(storage.value!).subscriptions[0].id;
    fireEvent.click(screen.getByRole('button', { name: '수정' }));
    fireEvent.change(screen.getByLabelText('금액 (원)'), { target: { value: '2000' } });
    fireEvent.click(screen.getByRole('button', { name: '취소' }));
    expect(await screen.findByText(/1,000원/)).toBeTruthy();
    fireEvent.click(screen.getByRole('button', { name: '수정' }));
    fireEvent.change(screen.getByLabelText('금액 (원)'), { target: { value: '2000' } });
    fireEvent.click(screen.getByRole('button', { name: '저장' }));
    await waitFor(() => expect(screen.getByText(/2,000원/)).toBeTruthy());
    expect(JSON.parse(storage.value!).subscriptions[0].id).toBe(id);
  });
  it('keeps the anchor and handles status and deletion failures', async () => {
    start();
    fireEvent.click(await screen.findByRole('button', { name: '첫 구독 추가' }));
    fireEvent.change(screen.getByLabelText('서비스명'), { target: { value: '영상' } });
    fireEvent.change(screen.getByLabelText('금액 (원)'), { target: { value: '1000' } });
    fireEvent.click(screen.getByRole('button', { name: '저장' }));
    fireEvent.click(await screen.findByRole('button', { name: /영상/ }));
    const anchor = JSON.parse(storage.value!).subscriptions[0].anchorDate;
    fireEvent.change(screen.getByLabelText('구독 상태'), { target: { value: 'PAUSED' } });
    await waitFor(() => expect(JSON.parse(storage.value!).subscriptions[0].status).toBe('PAUSED'));
    expect(JSON.parse(storage.value!).subscriptions[0].anchorDate).toBe(anchor);
    fireEvent.change(screen.getByLabelText('구독 상태'), { target: { value: 'ACTIVE' } });
    await waitFor(() => expect(JSON.parse(storage.value!).subscriptions[0].status).toBe('ACTIVE'));
    fireEvent.click(screen.getByRole('button', { name: '삭제' }));
    fireEvent.click(screen.getByRole('button', { name: '삭제 취소' }));
    expect(JSON.parse(storage.value!).subscriptions).toHaveLength(1);
    fireEvent.click(screen.getByRole('button', { name: '삭제' }));
    storage.fail = true;
    fireEvent.click(screen.getByRole('button', { name: '삭제 확인' }));
    expect(await screen.findByRole('alert')).toBeTruthy();
    expect(JSON.parse(storage.value!).subscriptions).toHaveLength(1);
    storage.fail = false;
    fireEvent.click(screen.getByRole('button', { name: '삭제 확인' }));
    await waitFor(() => expect(screen.getByText(/등록한 구독이 없어요/)).toBeTruthy());
    expect(JSON.parse(storage.value!).subscriptions).toHaveLength(0);
  });
  it('handles one native back per internal screen and removes its listener', async () => {
    const { unmount } = start();
    expect(storage.nativeBack).toBeUndefined();
    fireEvent.click(await screen.findByRole('button', { name: '첫 구독 추가' }));
    expect(storage.nativeBack).toBeTypeOf('function');
    storage.nativeBack!();
    expect(await screen.findByRole('button', { name: '첫 구독 추가' })).toBeTruthy();
    expect(storage.unlisten).toHaveBeenCalled();
    unmount();
  });
  it('shows read error and retries without overwriting data', async () => {
    storage.readFail = true;
    start();
    expect(await screen.findByRole('alert')).toBeTruthy();
    expect(screen.queryByRole('button', { name: '첫 구독 추가' })).toBeNull();
    storage.readFail = false;
    fireEvent.click(screen.getByRole('button', { name: '다시 시도' }));
    expect(await screen.findByRole('button', { name: '첫 구독 추가' })).toBeTruthy();
  });
  it('blocks native back while a write is pending', async () => {
    let finish!: () => void;
    storage.pending = new Promise<void>(resolve => { finish = resolve; });
    start();
    fireEvent.click(await screen.findByRole('button', { name: '첫 구독 추가' }));
    fireEvent.change(screen.getByLabelText('서비스명'), { target: { value: '저장 중' } });
    fireEvent.change(screen.getByLabelText('금액 (원)'), { target: { value: '1000' } });
    fireEvent.click(screen.getByRole('button', { name: '저장' }));
    expect(await screen.findByRole('button', { name: '저장 중' })).toBeTruthy();
    storage.nativeBack!();
    expect(screen.getByLabelText('서비스명')).toBeTruthy();
    finish();
    expect(await screen.findByRole('button', { name: /저장 중.*1,000원/ })).toBeTruthy();
  });
  it('shows loading while the initial read is pending', async () => {
    let finish!: () => void;
    storage.readPending = new Promise<void>(resolve => { finish = resolve; });
    start();
    expect(screen.getByText('기록을 불러오는 중이에요.')).toBeTruthy();
    finish();
    expect(await screen.findByRole('button', { name: '첫 구독 추가' })).toBeTruthy();
  });
  it('leaves only one native listener during StrictMode internal navigation', async () => {
    const add = vi.mocked(graniteEvent.addEventListener);
    add.mockClear();
    const { unmount } = render(<StrictMode><TDSMobileAITProvider brandPrimaryColor="#555555"><App /></TDSMobileAITProvider></StrictMode>);
    fireEvent.click(await screen.findByRole('button', { name: '첫 구독 추가' }));
    expect(add.mock.calls.length - storage.unlisten.mock.calls.length).toBe(1);
    unmount();
    expect(add.mock.calls.length).toBe(storage.unlisten.mock.calls.length);
  });
});
